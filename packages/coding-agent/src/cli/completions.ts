/**
 * Shell completion scripts generated from the CLI option table.
 *
 * Every script is derived from CLI_OPTIONS and CLI_COMMANDS, so new options and commands
 * are completed without shell-specific changes. Positional `@file` arguments complete
 * filesystem paths; plain message arguments are not completed.
 */

import { APP_NAME } from "../config.ts";
import { CLI_COMMANDS, CLI_OPTIONS, type CliOption, type CompletionShell } from "./options.ts";

/** `--` ends option parsing and is not something to complete. */
const COMPLETABLE_OPTIONS: readonly CliOption[] = CLI_OPTIONS.filter((option) => option.flag !== "--");
const COMMAND_NAMES = CLI_COMMANDS.map((command) => command.name);
/** Shell identifier derived from the binary name, e.g. `pi` -> `pi`. */
const IDENTIFIER = APP_NAME.replace(/[^A-Za-z0-9_]/g, "_");

function optionNames(option: CliOption): string[] {
	return [option.flag, ...option.aliases];
}

/** A value placeholder in square brackets, e.g. `[search]`, marks an optional value. */
function hasOptionalValue(option: CliOption): boolean {
	return option.value?.placeholder.startsWith("[") ?? false;
}

function generateBash(): string {
	const functionName = `_${IDENTIFIER}_completion`;
	const words = (values: readonly string[]) => `$'${values.join("\\n")}'`;
	const valueCases: string[] = [];
	for (const option of COMPLETABLE_OPTIONS) {
		const value = option.value;
		if (!value || hasOptionalValue(option)) continue;
		let reply = "COMPREPLY=()";
		if (value.choices) reply = `COMPREPLY=($(compgen -W ${words(value.choices)} -- "$cur"))`;
		else if (value.path === "directory") reply = `COMPREPLY=($(compgen -d -- "$cur"))`;
		else if (value.path === "file") reply = `COMPREPLY=($(compgen -f -- "$cur"))`;
		valueCases.push(`\t\t${optionNames(option).join("|")})\n\t\t\t${reply}\n\t\t\treturn\n\t\t\t;;`);
	}
	const flags = COMPLETABLE_OPTIONS.flatMap(optionNames);

	return `# bash completion for ${APP_NAME}. Generated by \`${APP_NAME} --completions bash\`.
${functionName}() {
	local cur="\${COMP_WORDS[COMP_CWORD]}"
	local prev="\${COMP_WORDS[COMP_CWORD-1]}"
	local IFS=$'\\n'

	case "$prev" in
${valueCases.join("\n")}
	esac

	if [[ "$cur" == @* ]]; then
		COMPREPLY=($(compgen -P @ -f -- "\${cur#@}"))
	elif [[ "$cur" == -* ]]; then
		COMPREPLY=($(compgen -W ${words(flags)} -- "$cur"))
	elif [[ $COMP_CWORD -eq 1 ]]; then
		COMPREPLY=($(compgen -W ${words(COMMAND_NAMES)} -- "$cur"))
	else
		case "\${COMP_WORDS[1]}" in
			${COMMAND_NAMES.join("|")})
				COMPREPLY=($(compgen -f -- "$cur"))
				;;
		esac
	fi
}
complete -o filenames -F ${functionName} ${APP_NAME}
`;
}

/** Quotes a string for a single-quoted POSIX shell word. */
function shellQuote(value: string): string {
	return `'${value.replace(/'/g, "'\\''")}'`;
}

function zshOptionSpecs(option: CliOption): string[] {
	const names = optionNames(option);
	const exclusions = option.repeatable ? "*" : `(${names.join(" ")})`;
	// Brackets and colons delimit the parts of an _arguments spec.
	const description = option.description[0].replace(/[\\[\]:]/g, "\\$&");
	let argument = "";
	const value = option.value;
	if (value) {
		const message = value.placeholder.replace(/[<>[\]:]/g, "");
		let action = "";
		if (value.choices) action = `(${value.choices.join(" ")})`;
		else if (value.path === "directory") action = "_directories";
		else if (value.path === "file") action = "_files";
		argument = `${hasOptionalValue(option) ? "::" : ":"}${message}:${action}`;
	}
	return names.map((name) => shellQuote(`${exclusions}${name}[${description}]${argument}`));
}

function generateZsh(): string {
	const functionName = `_${IDENTIFIER}`;
	const commands = CLI_COMMANDS.map((command) => `\t\t${shellQuote(`${command.name}:${command.description}`)}`);
	const specs = COMPLETABLE_OPTIONS.flatMap(zshOptionSpecs).map((spec) => `\t\t${spec} \\`);

	return `#compdef ${APP_NAME}
# zsh completion for ${APP_NAME}. Generated by \`${APP_NAME} --completions zsh\`.
${functionName}() {
	local context state state_descr line
	typeset -A opt_args
	local -a commands command_names
	commands=(
${commands.join("\n")}
	)
	command_names=(${COMMAND_NAMES.join(" ")})

	_arguments -C \\
${specs.join("\n")}
		'1: :->command' \\
		'*:: :->args'

	case $state in
		command)
			if compset -P '@'; then
				_files
			else
				_describe -t commands command commands
			fi
			;;
		args)
			if (( \${command_names[(Ie)$words[1]]} )); then
				_files
			elif compset -P '@'; then
				_files
			fi
			;;
	esac
}

if [[ $funcstack[1] == ${functionName} ]]; then
	${functionName} "$@"
else
	compdef ${functionName} ${APP_NAME}
fi
`;
}

/** Quotes a string for a single-quoted fish word. */
function fishQuote(value: string): string {
	return `'${value.replace(/[\\']/g, "\\$&")}'`;
}

function fishOptionLine(option: CliOption): string {
	const parts = [`complete -c ${APP_NAME}`];
	for (const alias of option.aliases) {
		// fish uses -s for single-letter short options and -o for multi-letter ones such as -nt.
		parts.push(alias.length === 2 ? `-s ${alias.slice(1)}` : `-o ${alias.slice(1)}`);
	}
	parts.push(`-l ${option.flag.slice(2)}`);
	const value = option.value;
	if (value && !hasOptionalValue(option)) {
		if (value.choices) parts.push(`-x -a ${fishQuote(value.choices.join(" "))}`);
		else if (value.path === "directory") parts.push("-x -a '(__fish_complete_directories)'");
		else if (value.path === "file") parts.push("-r -F");
		else parts.push("-x");
	}
	parts.push(`-d ${fishQuote(option.description[0])}`);
	return parts.join(" ");
}

function generateFish(): string {
	const atFiles = `__${IDENTIFIER}_complete_at_files`;
	const commands = CLI_COMMANDS.map(
		(command) =>
			`complete -c ${APP_NAME} -n __fish_use_subcommand -a ${command.name} -d ${fishQuote(command.description)}`,
	);

	return `# fish completion for ${APP_NAME}. Generated by \`${APP_NAME} --completions fish\`.
complete -c ${APP_NAME} -f

${commands.join("\n")}
complete -c ${APP_NAME} -n '__fish_seen_subcommand_from ${COMMAND_NAMES.join(" ")}' -F

${COMPLETABLE_OPTIONS.map(fishOptionLine).join("\n")}

function ${atFiles}
	set -l token (commandline -ct)
	string match -q -- '@*' $token; or return
	for path in (__fish_complete_path (string sub -s 2 -- $token))
		echo "@$path"
	end
end
complete -c ${APP_NAME} -n 'string match -q -- "@*" (commandline -ct)' -a '(${atFiles})'
`;
}

export function generateCompletionScript(shell: CompletionShell): string {
	switch (shell) {
		case "bash":
			return generateBash();
		case "zsh":
			return generateZsh();
		case "fish":
			return generateFish();
	}
}
